function getLargestDivisor ($nam) {
    if ($nam <= 1) return 0; // усливие для проверки меньши ли число или = 1
    for ($i = $nam - 1; $i >= 1; $i--) { // цыкл обратного отсчета (мен на 1)
        if ($nam % $i == 0) {
            return $i;
        }
    }
    return 1;
}
echo getLargestDivisor (100);
