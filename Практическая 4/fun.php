<?php
function getLargestDivisor ($num) {
    if ($num <= 1) return 0; // усливие для проверки меньши ли число или = 1
    for ($i = $num - 1; $i >= 1; $i--) { // цыкл обратного отсчета (мен на 1)
        if ($num % $i == 0) {
            return $i;
        }
    }
    return 1;
}
