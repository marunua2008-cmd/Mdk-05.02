?>
<h2> Инкремент и декремент</h2>
<?php
$b = 2;
$c = ++$b;
echo "b = $b, c = $c";
?>
<h2> Операции со строками</h2>
<?php
$str1 = 'Hello';
$str2 = 'PHP!';
$str3 = 'Я учусь  на' . 2 . 'курсе';
