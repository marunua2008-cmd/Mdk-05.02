?>
<h2> Логические операции</h2>
<p> Логическое И (&& abd), логическое И (|| or), логическое не ((!))</p>
<?php
$p = true && false; // false
$p1 = true || false; // true
$p2 = 5 <= 7 && 4 == 5; // false
$p3 = !$p2; // true
?>
